"""Create a SYNTHETIC fillable PDF (not an official form) for the fill_pdf tool.

Run: python -m scripts.make_synthetic_form
Output: procedures/ikamet_first/forms/preparation_sheet.pdf. It is a personal preparation sheet that
collects the facts a student needs at hand; it imitates no real authority's form.
"""
import pymupdf

from config import PROCEDURES_DIR

OUT = PROCEDURES_DIR / "ikamet_first" / "forms" / "preparation_sheet.pdf"
FIELDS = [
    ("holder_name", "Full name"),
    ("passport_number", "Passport or foreign ID number"),
    ("nationality", "Nationality"),
    ("passport_expiry", "Passport expiry date"),
    ("permit_start", "Requested permit start"),
    ("permit_end", "Requested permit end"),
    ("insurance_end", "Insurance coverage end"),
    ("institution", "Host institution"),
]


def main() -> None:
    document = pymupdf.open()
    page = document.new_page()
    page.insert_text((50, 60), "PERSONAL PREPARATION SHEET", fontsize=16)
    page.insert_text((50, 82), "Synthetic template generated by the Personal Bureaucracy Agent.", fontsize=9)
    page.insert_text((50, 95), "NOT an official form of any authority. Do not submit it.", fontsize=9)
    top = 130
    for index, (name, label) in enumerate(FIELDS):
        y = top + index * 36
        page.insert_text((50, y + 14), label, fontsize=10)
        widget = pymupdf.Widget()
        widget.field_name = name
        widget.field_type = pymupdf.PDF_WIDGET_TYPE_TEXT
        widget.rect = pymupdf.Rect(250, y, 545, y + 20)
        widget.text_fontsize = 10
        page.add_widget(widget)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    document.save(OUT)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
