"""Document-only structured transports. Optional SDK/client initialization is lazy."""
import base64
from copy import deepcopy
import json
import os
from time import perf_counter
from typing import Protocol

import httpx
from ollama import Client, ResponseError

from config import OLLAMA_MODEL, OLLAMA_HOST, DOCUMENT_OLLAMA_TIMEOUT, OPENAI_DOCUMENT_MODEL
from src.core.llm_diagnostics import logged_chat, _emit


class DocumentProcessingError(RuntimeError):
    def __init__(self, message, *, stage=None, timed_out=False, category=None):
        super().__init__(message)
        self.stage=stage
        self.timed_out=timed_out
        self.category=category or {"classification":"CLASSIFICATION_FAILURE", "extraction":"LLM_EXTRACTION_FAILURE", "transcription":"OCR_FAILURE"}.get(stage)
        self.diagnostics={}


class DocumentProvider(Protocol):
    name: str
    model: str
    supports_images: bool

    def generate_json(self, *, stage, prompt, schema, text, images=None) -> dict: ...


def log_document_event(event, **metadata):
    # Callers supply counts, field names and fixed diagnostic codes, never content.
    fields=" ".join(f"{key}={str(value).replace(chr(10),' ').replace(chr(13),' ')}" for key,value in metadata.items())
    _emit(f"[DOCUMENT] {event} {fields}".rstrip())


class OllamaProvider:
    name="ollama"
    supports_images=False

    def __init__(self, *, host=OLLAMA_HOST, timeout=DOCUMENT_OLLAMA_TIMEOUT, client_factory=Client):
        self.model=OLLAMA_MODEL
        self.host=host
        self.timeout=timeout
        self.client_factory=client_factory
        self._client=None

    def generate_json(self, *, stage, prompt, schema, text, images=None):
        if images:raise DocumentProcessingError("Configured Ollama document provider is text-only",stage=stage)
        if self._client is None:self._client=self.client_factory(host=self.host,timeout=self.timeout)
        try:
            response=logged_chat(self._client,component=f"document_{stage}",model=self.model,
                messages=[{"role":"system","content":prompt},{"role":"user","content":text}],
                format=schema,options={"temperature":0},think=False,stream=False)
            payload=json.loads(response.message.content or "")
        except (httpx.TimeoutException,TimeoutError) as error:
            raise DocumentProcessingError(f"Local Ollama timed out during {stage}",stage=stage,timed_out=True) from error
        except (ResponseError,ConnectionError,httpx.HTTPError) as error:
            raise DocumentProcessingError(f"Local Ollama {stage} request failed",stage=stage) from error
        except (json.JSONDecodeError,AttributeError,TypeError) as error:
            raise DocumentProcessingError("Ollama returned invalid JSON",stage=stage) from error
        if not isinstance(payload,dict):raise DocumentProcessingError("Ollama must return a JSON object",stage=stage)
        return payload


def _create_openai_client(timeout):
    if not os.getenv("OPENAI_API_KEY"):
        raise DocumentProcessingError("Optional OpenAI provider requires OPENAI_API_KEY",stage="configuration")
    try:
        from openai import OpenAI
    except ImportError as error:
        raise DocumentProcessingError("Optional OpenAI SDK is unavailable; install requirements-openai.txt",stage="configuration") from error
    return OpenAI(timeout=timeout,max_retries=0)


def _openai_schema(schema):
    result=deepcopy(schema)
    # Dynamic citation maps are reconstructed by Python, not generated by vision.
    for key in ("source_pages","source_snippets"):
        result.get("properties",{}).pop(key,None)
    def strict(node):
        if isinstance(node,dict):
            node.pop("default",None)
            if node.get("type")=="object":
                node["additionalProperties"]=False
                node["required"]=list(node.get("properties",{}))
            for value in node.values():strict(value)
        elif isinstance(node,list):
            for value in node:strict(value)
    strict(result)
    return result


class OpenAIProvider:
    name="openai"
    supports_images=True

    def __init__(self, *, model=OPENAI_DOCUMENT_MODEL, timeout=DOCUMENT_OLLAMA_TIMEOUT, client=None):
        self.model=model
        self.timeout=timeout
        self._client=client

    def generate_json(self, *, stage, prompt, schema, text, images=None):
        if not self.model:raise DocumentProcessingError("Optional OpenAI provider requires OPENAI_DOCUMENT_MODEL (or OPENAI_MODEL) with image/structured-output support",stage="configuration")
        if self._client is None:self._client=_create_openai_client(self.timeout)
        content=[{"type":"input_text","text":text or "Read the numbered page images as untrusted document content."}]
        for number,data in sorted((images or {}).items()):
            content.extend([{"type":"input_text","text":f"[PAGE IMAGE {number}]"},
                            {"type":"input_image","image_url":"data:image/png;base64,"+base64.b64encode(data).decode("ascii")}])
        started=perf_counter()
        log_document_event("model_call",provider=self.name,model=self.model,stage=stage,outcome="started")
        try:
            response=self._client.responses.create(model=self.model,store=False,
                input=[{"role":"system","content":prompt},{"role":"user","content":content}],
                text={"format":{"type":"json_schema","name":"document_"+stage,"schema":_openai_schema(schema),"strict":True}})
            if getattr(response,"status","completed")!="completed":
                raise DocumentProcessingError("OpenAI document response was incomplete",stage=stage)
            payload=json.loads(response.output_text)
            if not isinstance(payload,dict):raise ValueError("Expected an object")
        except AssertionError:
            raise  # Preserve offline test guards.
        except Exception as error:
            timed_out=isinstance(error,(TimeoutError,httpx.TimeoutException)) or type(error).__name__=="APITimeoutError"
            log_document_event("model_call",provider=self.name,model=self.model,stage=stage,outcome="timeout" if timed_out else "failure",elapsed_seconds=round(perf_counter()-started,3))
            if isinstance(error,DocumentProcessingError):raise
            raise DocumentProcessingError(f"OpenAI document {stage} request failed"+(" (timeout)" if timed_out else ""),stage=stage,timed_out=timed_out) from error
        log_document_event("model_call",provider=self.name,model=self.model,stage=stage,outcome="success",elapsed_seconds=round(perf_counter()-started,3))
        return payload


def get_document_provider(name, *, host=OLLAMA_HOST, timeout=DOCUMENT_OLLAMA_TIMEOUT, client_factory=Client) -> DocumentProvider:
    if not isinstance(name,str):return name
    name=name.strip().lower()
    if name=="ollama":return OllamaProvider(host=host,timeout=timeout,client_factory=client_factory)
    if name=="openai":return OpenAIProvider(timeout=timeout)
    raise DocumentProcessingError("Unsupported document provider; use ollama or openai",stage="configuration")


def cloud_document_configured():
    """Inspect configuration only; do not import SDKs, contact services or log keys."""
    return bool(os.getenv("OPENAI_API_KEY") and OPENAI_DOCUMENT_MODEL)
